"""Week 7 | HealthConnect Rwanda | Independent KPI validation.
Recomputes every headline KPI directly from the raw CSV files (pandas) and compares it with
(a) the Week 6 PostgreSQL value, and (b) the value shown in the Power BI dashboard (expected value in the DAX file).
Usage:  python3 week7_kpi_validation.py   (run from the Week7/Code folder; writes ../Evidence/kpi_validation.csv)
"""
import pandas as pd, os
D=os.path.join(os.path.dirname(__file__),'..','..','Data')
r=lambda n: pd.read_csv(os.path.join(D,f'HC_{n}.csv'),encoding='utf-8-sig')
pat,app,bil,dia,adm,fb,clm,pay=[r(x) for x in ['Patients','Appointments','Billing','Diagnoses','Admissions','Patient_Feedback','Insurance_Claims','Payments']]
staff=pd.concat([r(x).assign(Role=x) for x in ['Doctor','Nurse','Pharmacist','Radiographer','Laboratory_Scientist','Administrative_Staff']])
beds=r('Beds'); ref=r('Referrals'); lab=r('Laboratory_Tests')
paid=pay.groupby('BillingID').AmountPaid.sum()
b=bil.set_index('BillingID'); b['paid']=paid.reindex(b.index).fillna(0)
rev=bil.Amount.sum(); col=b.paid.sum()
adm_appts=app.AppointmentID.isin(adm.AppointmentID).sum()
k=[]
def add(name,val,dax,tol=0.0): k.append((name,val,dax,tol))
add('Total patients',len(pat),20000)
add('Total appointments',len(app),5000)
add('Patients seen (distinct)',app.PatientID.nunique(),4443)
add('Repeat patients (2+ visits)',int((app.PatientID.value_counts()>1).sum()),510)
add('Patients over 65',int((pat.Age>65).sum()),5487)
add('Average patient age',round(pat.Age.mean(),1),45.0,0.05)
add('Chronic patients',int(pat.ChronicCondition.fillna('None').ne('None').sum()),14929)
add('Total billed (RWF)',int(rev),9309401961)
add('Collected (RWF)',int(col),8389454556)
add('Outstanding (RWF)',int(rev-col),919947405)
add('Collection rate %',round(100*col/rev,1),90.1,0.05)
add('Average bill (RWF)',int(round(bil.Amount.mean())),155157)
add('Bills not fully paid',int(((b.Amount-b.paid)>0).sum()),11887)
add('Claims',len(clm),42036)
add('Claims approved',int((clm.Status=='Approved').sum()),21008)
add('Claim approval rate %',round(100*(clm.Status=='Approved').mean(),1),50.0,0.05)
add('Total diagnoses',len(dia),60000)
add('Severe rate %',round(100*(dia.Severity=='Severe').mean(),1),33.3,0.05)
add('Admissions rows',len(adm),5000)
add('Appointments with an admission',int(adm_appts),586)
add('Admission rate %',round(100*adm_appts/len(app),1),11.7,0.05)
add('Average length of stay (days)',round(adm.LengthOfStayDays.mean(),2),5.49,0.005)
add('Abnormal lab rate %',round(100*(lab.Result=='Abnormal').mean(),1),50.3,0.05)
add('Referrals',len(ref),4708)
add('Feedback rows',len(fb),21064)
add('Average rating (all)',round(fb.Rating.mean(),2),2.99,0.005)
add('Poor ratings (1-2) %',round(100*(fb.Rating<=2).mean(),1),40.5,0.05)
add('Total staff',len(staff),1250)
add('Doctors',int((staff.Role=='Doctor').sum()),350)
add('Nurses',int((staff.Role=='Nurse').sum()),700)
add('Beds',len(beds),2000)
add('Patients per staff member',round(len(pat)/len(staff),1),16.0,0.05)
add('Appointments per doctor',round(len(app)/350,2),14.29,0.005)
add('Bed utilisation % (estimate)',round(100*adm.LengthOfStayDays.sum()/(2000*365),1),3.8,0.05)
out=pd.DataFrame(k,columns=['kpi','recomputed_from_raw_csv','week6_expected_value','tolerance'])
out['difference']=(out.recomputed_from_raw_csv-out.week6_expected_value).round(3)
out['result']=['PASS' if abs(d)<=t+1e-9 else 'FAIL' for d,t in zip(out.difference,out.tolerance)]
os.makedirs('../Evidence',exist_ok=True); out.drop(columns='tolerance').to_csv('../Evidence/kpi_validation.csv',index=False)
print(out.drop(columns='tolerance').to_string(index=False)); print('\nPASS',(out.result=='PASS').sum(),'of',len(out))
